const INDIC_VIRAMA: Record<SupportedLang, string> = {
  en: '',
  ta: '்',
  te: '్',
  kn: '್',
  ml: '്',
  hi: '्',
};

function transliterateSingleToken(word: string, lang: SupportedLang): string {
  if (!word || lang === 'en') return word;
  let str = word.toLowerCase().trim();

  let matchedSuffix: { suf: string; res: string } | null = null;
  for (const [suf, map] of INDIC_SUFFIXES) {
    if (str.length > suf.length + 2 && str.endsWith(suf)) {
      matchedSuffix = { suf, res: map[lang] };
      str = str.slice(0, str.length - suf.length);
      break;
    }
  }

  let result = '';
  let i = 0;
  const len = str.length;

  while (i < len) {
    let matchedConsonant: Record<SupportedLang, string> | null = null;
    let consLen = 0;

    for (const cLen of [2, 1]) {
      if (i + cLen <= len) {
        const sub = str.slice(i, i + cLen);
        if (INDIC_CONSONANTS[sub]) {
          matchedConsonant = INDIC_CONSONANTS[sub];
          consLen = cLen;
          break;
        }
      }
    }

    if (matchedConsonant) {
      i += consLen;
      let matchedVowel: Record<SupportedLang, string> | null = null;
      let vowelLen = 0;

      for (const vLen of [2, 1]) {
        if (i + vLen <= len) {
          const sub = str.slice(i, i + vLen);
          if (INDIC_VOWEL_SIGN[sub]) {
            matchedVowel = INDIC_VOWEL_SIGN[sub];
            vowelLen = vLen;
            break;
          }
        }
      }

      if (matchedVowel) {
        result += matchedConsonant[lang] + matchedVowel[lang];
        i += vowelLen;
      } else {
        result += matchedConsonant[lang] + INDIC_VIRAMA[lang];
      }
    } else {
      let matchedIndep: Record<SupportedLang, string> | null = null;
      let indepLen = 0;

      for (const vLen of [2, 1]) {
        if (i + vLen <= len) {
          const sub = str.slice(i, i + vLen);
          if (INDIC_VOWEL_INDEP[sub]) {
            matchedIndep = INDIC_VOWEL_INDEP[sub];
            indepLen = vLen;
            break;
          }
        }
      }

      if (matchedIndep) {
        result += matchedIndep[lang];
        i += indepLen;
      } else {
        result += str[i];
        i++;
      }
    }
  }

  if (matchedSuffix) {
    result += matchedSuffix.res;
  }

  return result;
}

export function transliterateIndic(text: string, lang: SupportedLang): string {
  if (!text || lang === 'en') return text;
  const tokens = text.split(/(\s+|-)/);
  return tokens
    .map(t => {
      if (!t.trim() || t === '-') return t;
      return transliterateSingleToken(t, lang);
    })
    .join('');
}

export function normalizeKey(text: string | null | undefined): string {
  return (text || '')
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]/g, '');
}

/**
 * Translates an Indian state name or state ISO code into the active language.
 */
export function translateState(
  stateNameOrCode: string | null | undefined,
  lang: string = 'en',
): string {
  if (!stateNameOrCode) return '';
  const cleanLang = (lang || 'en').toLowerCase().slice(0, 2) as SupportedLang;
  if (cleanLang === 'en') return stateNameOrCode;

  const rawUpper = stateNameOrCode.trim().toUpperCase();
  const stateKeyFromCode = STATE_CODE_MAP[rawUpper];
  const stateKey = stateKeyFromCode || normalizeKey(stateNameOrCode);

  const entry = STATE_DICTIONARY[stateKey];
  if (entry && entry[cleanLang]) {
    return entry[cleanLang];
  }

  return stateNameOrCode;
}

/**
 * Translates an Indian city name into the active language.
 * Checks the comprehensive city dictionary first, then falls back
 * to the universal Indic transliteration engine so no city ever remains in raw English.
 */
export function translateCity(
  cityName: string | null | undefined,
  lang: string = 'en',
): string {
  if (!cityName) return '';
  const cleanLang = (lang || 'en').toLowerCase().slice(0, 2) as SupportedLang;
  if (cleanLang === 'en') return cityName;

  const cityKey = normalizeKey(cityName);
  const entry = CITY_DICTIONARY[cityKey];
  if (entry && entry[cleanLang]) {
    return entry[cleanLang];
  }

  // Universal Indic transliteration fallback
  return transliterateIndic(cityName, cleanLang);
}

/**
 * Returns translated state options for dropdowns.
 */
export function getTranslatedStates(lang: string = 'en') {
  return indianStates.map((s) => ({
    key: s.isoCode,
    canonicalName: s.name,
    label: translateState(s.name, lang),
  }));
}

/**
 * Returns translated city options for a given state code or name.
 */
export function getTranslatedCities(stateCodeOrName: string, lang: string = 'en') {
  if (!stateCodeOrName) return [];
  const normalized = normalizeKey(stateCodeOrName);
  const state = indianStates.find(
    (s) =>
      s.isoCode.toUpperCase() === stateCodeOrName.trim().toUpperCase() ||
      normalizeKey(s.name) === normalized,
  );
  const code = state ? state.isoCode : stateCodeOrName;
  const rawCities = getCities(code) || [];
  return rawCities.map((c: any) => ({
    key: c.name,
    canonicalName: c.name,
    label: translateCity(c.name, lang),
  }));
}

/**
 * Reverse lookup: converts a translated Indic city label back to canonical English name.
 */
export function getCanonicalCity(cityNameOrLabel: string): string {
  if (!cityNameOrLabel || !cityNameOrLabel.trim()) return '';
  const trimmed = cityNameOrLabel.trim();
  if (!/[^\x00-\x7F]/.test(trimmed)) {
    return trimmed;
  }
  const lower = trimmed.toLowerCase();
  for (const [key, entry] of Object.entries(CITY_DICTIONARY)) {
    if (Object.values(entry).some(val => val.toLowerCase() === lower)) {
      return entry.en || key;
    }
  }
  return trimmed;
}
